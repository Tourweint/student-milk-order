package com.milk.order.process.invariant;

import java.util.List;

/**
 * 业务过程不变量（运行期持续验证的检查项）。
 *
 * <p><b>为什么要它：</b>系统里存在一批「跨表约束」，它们不是主键外键能表达的，只能靠代码自觉维护，
 * 例如“配额已售数必须等于台账合计”“任务已完成则签收记录必须已签收”。
 * 实验只能验证它们在某个时刻成立，而运行期的业务过程是持续的——不变量只在被验证时才成立。
 * 因此把每条跨表约束写成可注册的检查项，由体检任务周期求值。</p>
 *
 * <p><b>实现位置约定：</b>检查项放在拥有该数据的业务模块（探测 SQL 与修复动作都依赖本模块），
 * 过程层只提供接口、注册表、体检调度与记录，因此过程层依然不依赖任何业务表。</p>
 */
public interface ProcessInvariant {

    /** 不变量编码（唯一，写入体检记录，如 INV_QUOTA_LEDGER） */
    String code();

    /** 中文描述（说明“应当成立什么”，写进体检记录与报告） */
    String description();

    /**
     * 处置等级的**默认值**。
     *
     * <p>当同一条不变量的不同违规需要不同处置时，{@link #detect} 可以在每条
     * {@link InvariantViolation} 上覆写自己的等级——例如「父过程已终态但存在非终态子过程」：
     * 待配送的子任务可以自动作废，配送中的子任务（奶已出库在途）只能告警。
     * 体检器以**每条违规的实际等级**决定是否自动修复。</p>
     */
    InvariantSeverity severity();

    /**
     * 执行顺序依赖：本检查项必须在这些编码的检查项**之后**执行（默认无依赖）。
     *
     * <p><b>为什么需要它：</b>不变量之间不是彼此独立的，修复动作会互相影响。典型例子是
     * 「子过程补全」与「父过程聚合」——父聚合的判定依据是"子任务是否全部终态"，
     * 若先判父、再补子，父状态就可能建立在"当时完整、随后被补"的子集合上。
     * 之前这层顺序只靠编码字典序**碰巧**排对，一旦新增一条编码靠前的不变量就会失序。
     * 声明式依赖把"顺序"从命名巧合变成可审阅的约束。</p>
     *
     * <p>体检器按拓扑序执行；存在环路或引用了未注册的编码时**快速失败**（不静默降级为任意顺序）。</p>
     */
    default List<String> dependsOn() {
        return List.of();
    }

    /**
     * 只读探测：返回违反该不变量的主体清单。
     *
     * <p><b>契约：</b>不得修改任何数据。探测可以被随时调用（体检、实验、人工排查），
     * 因此它必须无副作用、可重复、可限批。</p>
     *
     * @param limit 最多检出多少条（防止历史脏数据拖死体检任务）
     */
    List<InvariantViolation> detect(int limit);

    /**
     * 修复单条违规（幂等，可重复调用）。
     *
     * <p><b>契约：</b>修复必须复用业务侧的既有出口（如统一迁移出口、配额回算），
     * 不得绕过可靠性层直接改状态——否则修复本身会成为新的旁路。</p>
     *
     * @return true 表示本次修复生效；false 表示无需修复或前置条件已不满足（如已被并发修复）
     */
    boolean repair(InvariantViolation violation);
}
